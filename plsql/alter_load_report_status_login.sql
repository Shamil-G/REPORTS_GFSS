-- Владелец запуска в журнале готовых отчётов.
--
-- Нужен, чтобы в списке созданных отчётов каждый видел свои запуски и мог
-- скачать только свои файлы (ACCESS-PLAN.md, этап 3). Прежде в
-- LOAD_REPORT_STATUS не было ни владельца, ни признака филиала запускавшего:
-- строки всех пользователей лежали вперемешку и были видны всем.
--
-- login_name - имя входа из SSO (session['username']), то же, что пишется в
-- журнал доступа util.log_reports.
--
-- Порядок: сначала этот скрипт, затем reps.pck, и только потом перезапуск
-- приложения - его код уже рассчитывает на колонку.
-- У строк, созданных до изменения, владелец пустой: их видит только
-- администратор.

alter table LOAD_REPORT_STATUS add (login_name varchar2(64));

comment on column LOAD_REPORT_STATUS.login_name is 'Имя входа пользователя, запустившего отчёт (SSO)';
