-- Подразделение, запустившее отчёт, в журнале готовых отчётов.
--
-- Нужно, чтобы в списке созданных отчётов департамент видел свои запуски и
-- скачивал свои файлы, а чужие не видел (ACCESS-PLAN.md, этап 3). Прежде в
-- LOAD_REPORT_STATUS не было ни подразделения, ни пользователя: строки всех
-- лежали вперемешку и были видны всем.
--
-- ou_name - короткое имя подразделения из AD (DAUiS, DpRsP, DITiTO), то же,
-- что приходит из SSO и стоит в правах доступа к разделам каталога.
--
-- Порядок: сначала этот скрипт, затем reps.pck, и только потом перезапуск
-- приложения - его код уже рассчитывает на колонку.
-- У строк, созданных до изменения, подразделение пустое: их видит только
-- администратор.

alter table LOAD_REPORT_STATUS add (ou_name varchar2(64));

comment on column LOAD_REPORT_STATUS.ou_name is 'Подразделение (ou_name из AD), запустившее отчёт';
