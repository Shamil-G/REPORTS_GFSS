# -*- coding: utf-8 -*-
"""5001. Социальная напряженность, область (свод по областям).

Перенос SOCIAL_TENSION.report_1 (схема DASORP, пакет «Социальная напряженность»,
AIS 5001 «Свод по областям»). Группа «5000 - Социальная напряженность» (ДИА):
группа 3200 принимает только 3201-3299 (Шамиль, 13.10.2026). Расчёт, общий для
5001-5006, - в `util/social_tension.py`; там же описано, что считается и чем
источники отличаются от оригинала.

Строка отчёта - область: сколько плательщиков всего, сколько из них со
снижением (`perc > 0`), распределение снизивших по полосам 0-10 ... 90+ %
(`perc >= нижняя and < верхняя`, первая полоса `perc > 0`), сколько снизили
на 50 % и более и их доля к числу плательщиков области.

Отличия от оригинала (дополнительно к перечисленным в util/social_tension.py):
  - период выбирается в форме (дата «с» и «по», месяцы берутся по датам; первый
    месяц - база, месяц даты «по» - сравниваемый). Оригинал был привязан к
    sysdate (предпоследний и последний закрытый месяц); `set_date` в боевой
    БД к тому же была оставлена с датами 2023 года;
  - названия областей - `branch.name` записи `XX00` («Акмолинская область»,
    «г. Алматы»). `cato_branch.name_ru` не годится: у новых областей там
    казахские формы с утраченными буквами («ОБЛАСТЬ ?ЛЫТАУ», «ОБЛАСТЬ ЖЕТІСУ»).
    В оригинале названия шли из `rfrg_region`: короткие, без слова «область», с
    подменой казахской буквы («Ўлытау») и пробелом в конце («Туркестанская »),
    а у четырёх разделённых областей - полные;
  - «Доля» - доля (0,055), формат ячейки показывает «5,5%», одна цифра после
    запятой, как в оригинале (`number(16,1)`). Итог по ней - доля сумм
    (`avg_of`: сумма «от 50% и более» / сумма «Всего»; за июль-август 2026
    925 / 16 835 = 5,5%), а не сумма процентов по областям, как в оригинале
    (`SetColSumTotal(16)`, там выходило 106,4 - число без смысла; Шамиль, 14.10.2026);
  - «допустивших  снижение» (двойной пробел) в заголовке - один пробел;
  - подписи «Руководитель / Исполнитель / дата и время создания» под таблицей
    не переносятся: дата формирования стоит в шапке листа.
Колонку «№» ставит рендерер. Порядок строк - по коду области (01..20), в
оригинале по названию (`order by 1`): при названиях КАТО «ОБЛАСТЬ АБАЙ» /
«Г.АЛМАТЫ» алфавит перемешал бы области и города.
"""
from db.connect import LOADER_PROFILE
from util.social_tension import base_for, BANDS, OBL_JOIN, OBL_NAME, band_columns, band_sql, check_params, normalize_params
from util.xlsx_report import build_report, Col, Group

report_code = '5001'
report_name = 'Социальная напряженность, Области. На период с {date_from} по {date_to}'

COLUMNS = [
    Col('Обл', 'reg', 'text', 36),
    Group('Кол-во плательщиков, уплачивающих СО', [
        Col('Всего', 'cnt_all', 'int', 12),
        Col('В том числе со снижением', 'cnt_dis', 'int', 14),
    ]),
    Group('Кол-во плательщиков допустивших снижение участников СОСС', band_columns()),
    Col('Кол-во плательщиков уплачивающих СО, допустивших снижение '
        'участников СОСС от 50% и более (единиц)', 'cnt50', 'int', 20),
    Col('Доля плательщиков уплачивающих СО, допустивших снижение, к общему '
        'количеству плательщиков уплачивающих СО в регионе, %', 'dolya',
        'pct', 20, avg_of=('cnt50', 'cnt_all')),
]

def STMT(params):
    base = base_for(params, with_sect=False)
    return f"""
with {base.lstrip()},
agg as (
    select c.obl,
           count(*) cnt_all,
           count(case when c.perc > 0 then 1 end) cnt_dis,
           {band_sql('c')},
           count(case when c.perc >= 50 then 1 end) cnt50
      from calc c
     group by c.obl
)
select {OBL_NAME} reg,
       a.cnt_all, a.cnt_dis,
       {', '.join(f'a.b{i}' for i in range(len(BANDS)))},
       a.cnt50,
       round(a.cnt50 / a.cnt_all, 3) dolya
  from agg a, branch b
 where {OBL_JOIN}
 order by a.obl
"""

do_report, thread_report = build_report(
    code=report_code, name=report_name, columns=COLUMNS, stmt=STMT,
    profile=LOADER_PROFILE, date_range=True, check_params=check_params,
    totals=True,
)
