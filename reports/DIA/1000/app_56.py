"""Приложение 56. Динамика перехода степеней утраты трудоспособности
получателей социальных выплат на случай утраты трудоспособности (0702).

Перенос REP_STAT_EXTEND.app_56_spool + Rep_app_56 (pck_utf8.sql, 11951-12220).
Протокол: 4 запуска, последний 04.2023. Вызов в вебе: группа 1560, id 1561
(только месячный). Источник оригинала - rptb_dinamika_detail_ext, замёрзшая на
01.12.2021 пакетом REP_STAT_EXTEND_DINAMIKA.

ПЕРЕСТРОЕНО, а не перенесено буквально (Шамиль, 01.10.2026: делаем app_56/57).
Оригинал считал строки-события из детальной таблицы, и его столбцы не имели
однозначного смысла: "на начало периода" - число строк-событий кроме прибытий
(graf_id не 7, 8, 9: сюда попадали и убывшие, и изменения суммы, и
восстановленные), "на конец" - строк кроме убытий (14, 15, 16); строка группы
определялась символом 5 тега перехода, то есть ТЕКУЩЕЙ группой, а не прежней
(тег ММММТП: Т - текущая, П - предыдущая). Воспроизвести такие числа по
живым данным нельзя, поэтому здесь однозначные определения (dyn_matrix.py):
  строка                 - степень на начало месяца;
  на начало периода      - получателей этой степени в прошлом месяце;
  80-100 / 60-80 / 30-60 - из них в этом месяце оказались в указанной степени
                           (диагональ пуста, как в оригинале: i_stag = k);
  прибыло / убыло        - ВСЕ пришедшие / ушедшие (в оригинале 7, 8, 9 и
                           14, 15, 16, без восстановленных и снятых без акта);
  на конец периода       - получателей этой степени в этом месяце.
Источник - pnpd_document (как Fill_F11), группа - последний символ rfpm_id.
Нужны подтверждение определений Шамилем и проверка допущения про формат rfpm_id.
Ветка шапки 'f' ("Форма № 27") не переносится.
"""
import importlib

from db.connect import LOADER_PROFILE
from util.period import make_period_label
from util.xlsx_report import build_report, Col, Group
# имя пакета `reports.DIA.1000` начинается с цифр, обычный import не годится
matrix_stmt = importlib.import_module('reports.DIA.1000.dyn_matrix').matrix_stmt

report_code = 'APP.56'
# cSPTitle || PH_per (строки 12077, 12215)
report_name = ('Динамика перехода степеней утраты трудоспособности получателей '
               'социальных выплат на случай утраты трудоспособности{period}')
_period_label = make_period_label({1: ', за {Month} {year} года '})

_ROWS = ['степень утраты трудоспособности от 80% до 100%',
         'степень утраты трудоспособности от 60% до 80%',
         'степень утраты трудоспособности от 30% до 60%']

COLUMNS = [
    Col('Имеющееся степень утраты трудоспособности', 'kat', 'text', 46),
    Col('Количество получателей СВут на начало отчетного периода, чел.',
        'cnt_old', 'int', 20),
    Group('Количество* получателей  СВут, чел.', [
        Col(name, f'gr{k}', 'int', 20) for k, name in enumerate(_ROWS, start=1)
    ]),
    Col('Всего прибыло, чел.', 'cnt_in', 'int', 14),
    Col('Всего убыло, чел.', 'cnt_out', 'int', 14),
    Col('Количество получателей СВут на конец отчетного периода, чел.',
        'cnt_now', 'int', 20),
]

FOOTNOTE = ('* - численность получателей, у которых изменилась степень утраты '
            'трудоспособности в отчетном  периоде.')

STMT = matrix_stmt('0702', _ROWS)

do_report, thread_report = build_report(
    code=report_code, name=report_name, columns=COLUMNS, stmt=STMT,
    profile=LOADER_PROFILE, period=True, totals=False, blank_zero=False,
    period_label=_period_label, footnote=FOOTNOTE,
)
