# -*- coding: utf-8 -*-
"""8028. Количество плательщиков, допустивших снижение количества участников
СОСС на 50% и более.

Перенос WEB_REP_R_8028 (AIS 8028, группа 8000 «Паспорт СОСС», «ДРП»). Образец -
`docs/8000/Rep__8028.xlsx`.

Оригинал читал таблицу `rep_8028`, в которую никакой код БД не пишет (ни
процедуры, ни задания, ни зависимости в SSWH): строка «Январь 2025 г. к
Декабрю 2024 г.» - 13 567 / 6 676 / 1 161 - введена вручную. По смыслу это три
счётчика над `social_tension_calculate_all` (её строит SOCIAL_TENSION.run,
тот же расчёт, что у 5001-5006 и 8024): всего плательщиков со штатной
численностью от 50 человек в базовом месяце, из них со снижением числа
участников (`perc > 0`) и со снижением на 50 % и более. Здесь они считаются из
данных тем же расчётом, что 5001 (`util/social_tension.py`; плательщик и место
- `rfon_organization` и `cato_branch`): базовый месяц - предыдущий перед
выбранным, сравниваемый - выбранный.

Числа поэтому не совпадут с ручной строкой: на декабрь 2024 / январь 2025 этот
расчёт даёт другую базу плательщиков (она тогда строилась по `rfrr_id_region`).
Проверка старой логики на текущих данных дала 13 912 / 6 087 / 498 - тоже не
13 567 / 6 676 / 1 161, то есть повторить ручную строку нельзя ни тем, ни
другим способом.
"""
from db.connect import LOADER_PROFILE
from util.social_tension import BASE
from util.xlsx_report import build_report, Col, Group

report_code = '8028'
report_name = ('Количество плательщиков, допустивших снижение количества\n'
               'участников СОСС на 50% и более (8028, ДРП)')

COLUMNS = [
    Col('Сравнение уплаты СО за отчётный\nмесяц к предыдущему месяцу', 'period',
        'text', 40),
    Group('Количество плательщиков', [
        Col('Всего', 'cnt_p', 'int', 14),
        Col('в т.ч. уплативших\nсо снижением кол-\nва участников\nСОСС',
            'cnt_r', 'int', 20),
    ]),
    Col('Количество\nплательщиков,\nуплативших СО со\nснижением\n'
        'количества\nучастников СОСС\nна 50% и более', 'cnt_50', 'int', 22),
]

# базовый месяц - предыдущий перед выбранным (:d_from периода - первое число
# выбранного месяца)
_BASE = BASE.replace(':d_from', 'add_months(:d_from, -1)')

# название месяца: именительный для отчётного, дательный для предыдущего
_MON_NOM = ("decode(extract(month from {d}), 1, 'Январь', 2, 'Февраль', "
            "3, 'Март', 4, 'Апрель', 5, 'Май', 6, 'Июнь', 7, 'Июль', "
            "8, 'Август', 9, 'Сентябрь', 10, 'Октябрь', 11, 'Ноябрь', 'Декабрь')")
_MON_DAT = ("decode(extract(month from {d}), 1, 'Январю', 2, 'Февралю', "
            "3, 'Марту', 4, 'Апрелю', 5, 'Маю', 6, 'Июню', 7, 'Июлю', "
            "8, 'Августу', 9, 'Сентябрю', 10, 'Октябрю', 11, 'Ноябрю', 'Декабрю')")

STMT = f"""
with {_BASE.lstrip()}
select {_MON_NOM.format(d=':d_from')} || ' ' || extract(year from :d_from)
       || ' г. к ' ||
       {_MON_DAT.format(d='add_months(:d_from, -1)')} || ' '
       || extract(year from add_months(:d_from, -1)) || ' г.' period,
       count(*) cnt_p,
       count(case when perc > 0 then 1 end) cnt_r,
       count(case when perc >= 50 then 1 end) cnt_50
  from calc
"""

do_report, thread_report = build_report(
    code=report_code, name=report_name, columns=COLUMNS, stmt=STMT,
    profile=LOADER_PROFILE, period=True,
)
