# -*- coding: utf-8 -*-
"""СВБР, таблица 1: получатели в разрезе стажа участия.

Перенос REP_STAT_EXTEND.svbr_tab1_2_spool (таблица 1) + svbr_tab1_2.Prn_SP
(таблица 1, pck_utf8.sql, 13250-13340 - расчёт; 13584-13633 - вывод).
Реестр: группа 2020, вызов svbr_tab1_2_1m и аналоги по типам периода 1-5
(без второго аргумента 'm'/'f' - у процедуры его нет вовсе).

Оригинал печатает ДВЕ разных таблицы одним прогоном (Prn_SP печатает
Таблицу 1, затем Таблицу 2 - разные колонки, разные источники строк) - это
два отдельных модуля, svbr_tab1.py и svbr_tab2.py, а не один: наш
build_report описывает ровно одну таблицу на отчёт, и колонки/строки этих
двух совсем разные. Третья таблица, которую считает spool (value_type
138-140, "коэффициент дней нетрудоспособности") - НЕ переносится: в
Rep_svbr_tab1_2 (строки 13692-13726 - копипаста блока "Таблица 2" с тем же
заголовком "Таблица 2." и теми же value_type 118/119) она никогда не
читает своих собственных данных 138-140 - мёртвый вывод, настоящих данных
не показывает.

Источник - `sipr_payer` (текущий реестр назначений, НЕ
sipr_maket_first_approve_2, как почти везде), state in (12,13) - коды
статуса не задокументированы в комментариях исходника, перенесены как
есть. Вид выплаты (LIST_RFPM) сравнивается через LIKE (`rfpm_id like
:rfpm_id || '%'`), а не точным substr(...,1,4) - значит, например, для
0704 сюда попадёт и 070403 (в отличие от большинства других отчётов, где
070403 отделяется явно) - сохранено дословно (строка 13312 оригинала:
`rfpm_id like '''||iTypePay||'%'''`).

Стаж участия (count_donation) здесь НЕ разбит на фиксированные бакеты, как
в других отчётах - строки таблицы это просто различные значения
count_donation, встретившиеся в данных за период, по возрастанию (строки
13560-13574: idx считается по факту найденных строк, без справочника и
без заполнения "дыр").
"""
from db.connect import LOADER_PROFILE
from util.period import make_period_label
from util.xlsx_report import build_report, Col

report_code = 'SVBR.TAB1'
report_name = '{rfpm_id}{period}'

# cSPT0701..0705 дословно (строки 13581-13585 - все заканчиваются ", за ").
_RFPM_TEXT = {
    '0701': 'Получатели СВ по потери кормильца, за ',
    '0702': 'Получатели СВ по утраты трудоспособности, за ',
    '0703': 'Получатели СВ по потери работы, за ',
    '0704': ('Получатели СВ по потери дохода в связи с беременностью и '
             'родами, с усыновлением (удочерением) новорожденного ребенка '
             '(детей), за '),
    '0705': ('Получатели СВ по потери дохода в связи с уходом за ребенком '
             'по достижении им возраста одного года, за '),
}

# Begin блок svbr_tab1_2 (строки 13569-13577) - тип 4 (9 месяцев) в
# оригинале ПРОПУЩЕН (нет ветки вовсе - при вызове за 9 месяцев подпись
# периода была бы пустой). Восполнено по аналогии с остальными типами.
_period_label = make_period_label({
    1: '{Month} месяц {year} года ',
    2: '{n} квартал {year} года ',
    3: '{n} полугодие {year} года ',
    4: '9 месяцев {year} года ',
    5: '{year} год ',
})

COLUMNS = [
    Col('Стаж участия', 'staj', 'text', 14),
    Col('Кол-во получателей (чел.)', 'cnt_p', 'int'),
    Col('СМД (тг)', 'sm_avg', 'money', 16),
    Col('Общая сумма СВбр (тг)', 'sm_svbr', 'money', 18),
]

# :d_from / :d_to - границы отчётного периода, :d_to исключительная.
# :rfpm_id - выбранный вид выплаты (LIST_RFPM), сравнение через LIKE.
STMT = """
select to_char(count_donation) staj,
       count(1)                cnt_p,
       sum(sum_avg)            sm_avg,
       sum(sum_all)            sm_svbr
  from sipr_payer
 where rfpm_id like :rfpm_id || '%'
   and state in (12, 13)
   and sum_all > 0
   and risk_date >= :d_from
   and risk_date <  :d_to
 group by count_donation
 order by count_donation
"""

do_report, thread_report = build_report(
    code=report_code, name=report_name, columns=COLUMNS, stmt=STMT,
    profile=LOADER_PROFILE, period=True, totals=True, blank_zero=True,
    period_label=_period_label, sheet_name='Таблица 1',
    text_params={'rfpm_id': _RFPM_TEXT},
)
