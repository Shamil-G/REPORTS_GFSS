"""Признак «город / район (село)» у отделения (`rfbn_branch`).

Получатель выплаты хранится с отделением (`rfbn_id`), а не с КАТО, поэтому
признак относится к ОТДЕЛЕНИЮ, а не к месту жительства получателя: районное
отделение включает и райцентр, и сёла.

`cato_branch.lev` город от села не отделяет - это глубина иерархии КАТО
(2 - район или город областного значения, 3-5 - округа и пункты), город
виден только по префиксу названия («Г.А.», «Г.»). Поэтому правило такое:
город, если выполнено любое из условий:
  - в названии отделения «городск...» или оно начинается с «г.»
    («Кокшетауское городское отделение», «г. Алматы Алмалинское отделение»);
  - запись КАТО отделения (`cato_branch`, lev = 2, `rfbn_id` совпадает) названа
    «... Г.А.» (город областного значения: «Районное отделение г.Арыс»,
    «Атырауский областной филиал»);
  - родитель этой записи (lev = 1) - город республиканского значения
    (Г.АСТАНА, Г.АЛМАТЫ, Г.ШЫМКЕНТ): их районы в КАТО названы «... РАЙОН»,
    а «Нуринское районное отделение» - район Астаны.
Остальное - «Село» (районное отделение, включая райцентр). На 13.10.2026: 58 отделений - город, 166 - район.
Отделения без записи КАТО (1403, 1420, 1422, 1508) определяются по названию.
"""
CITY = 'Город'
RURAL = 'Село'


def branch_kind(branch='br', cato='cb', parent='cp'):
    """(выражение, таблицы для from, условия для where, добавка к group by).

    branch - алиас rfbn_branch в запросе. Выражение зависит от br.name,
    cb.name_ru и cp.name_ru, поэтому при group by их нужно добавить в группу
    (см. `group_by`).
    """
    expr = (f"case when upper({branch}.name) like '%ГОРОДСК%'\n"
            f"                 or upper({branch}.name) like 'Г.%'\n"
            f"                 or upper({cato}.name_ru) like '%Г.А.%'\n"
            f"                 or upper({parent}.name_ru) like 'Г.%'\n"
            f"            then '{CITY}' else '{RURAL}' end")
    tables = f"cato_branch {cato}, cato_branch {parent}"
    where = (f"{cato}.rfbn_id(+) = {branch}.rfbn_id and {cato}.lev(+) = 2\n"
             f"   and {parent}.code(+) = {cato}.par_code")
    group_by = f"{cato}.name_ru, {parent}.name_ru"
    return expr, tables, where, group_by
